"""Create disposable reviewer/publisher identities and one invented sheet row for browser QA.

Never use on a real database. Credentials are generated by CI, passed only by environment,
and are never logged or written in the repository.
"""

import csv
import io
import os

from django.conf import settings
from django.contrib.auth import get_user_model
from django.contrib.auth.models import Permission
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from catalog.crosswalk import stage_snapshot
from catalog.models import Source
from catalog.sheets import load_contract

SOURCE_KEY = "fictional-review-browser"
SOURCE_LICENSE = "Original invented browser-review exercise; no SOS MEDITERRANEE event."
REVIEWER = "__fictional_review_browser__"
PUBLISHER = "__fictional_publish_browser__"


class Command(BaseCommand):
    help = "Create strictly fictional, isolated volunteer-review E2E fixtures"

    def add_arguments(self, parser):
        parser.add_argument("--confirm-local-training", action="store_true")

    @transaction.atomic
    def handle(self, *args, **options):
        password = os.environ.get("KICKOFF_REVIEW_PASSWORD", "")
        if (
            not options["confirm_local_training"]
            or not settings.DEBUG
            or settings.DATA_MODE != "training"
            or len(password) < 20
        ):
            raise CommandError(
                "Refused: development/training/explicit flag and a test-only password required"
            )

        source, _ = Source.objects.get_or_create(
            key=SOURCE_KEY,
            defaults={
                "name": "SYNTHETIC browser review source",
                "url": "https://example.org/browser-review/",
                "license_note": SOURCE_LICENSE,
                "synthetic": True,
                "rights_approved": True,
            },
        )
        if (
            not source.synthetic
            or not source.rights_approved
            or source.license_note != SOURCE_LICENSE
        ):
            raise CommandError("Refused: source name already used by non-fixture data")

        model = get_user_model()
        users = {}
        roles = {
            REVIEWER: ("review_identity", "add_sheetsnapshot"),
            PUBLISHER: ("add_event", "publish_event"),
        }
        for username, codenames in roles.items():
            user, created = model.objects.get_or_create(
                username=username,
                defaults={"is_active": True, "is_staff": False, "is_superuser": False},
            )
            if not created and (
                user.is_staff or user.is_superuser or not user.check_password(password)
            ):
                raise CommandError("Refused: browser test account collision")
            if created:
                user.set_password(password)
                user.save(update_fields=["password"])
            user.user_permissions.add(
                *[
                    Permission.objects.get(content_type__app_label="catalog", codename=codename)
                    for codename in codenames
                ]
            )
            users[username] = model.objects.get(pk=user.pk)

        headers = [
            column["name"] for column in load_contract()["sheets"]["Data_operations"]["columns"]
        ]
        cells = {
            "date": "17/01/2026",
            "type_ops": "Rescue",
            "nb_survivor": "18",
            "latitude": "35.10",
            "longitude": "12.60",
        }
        buffer = io.StringIO(newline="")
        writer = csv.writer(buffer, lineterminator="\n")
        writer.writerow(headers)
        writer.writerow([cells.get(name, "") for name in headers])
        snapshot, _ = stage_snapshot(
            source=source,
            sheet="Data_operations",
            content=buffer.getvalue().encode("utf-8"),
            actor=users[REVIEWER],
        )
        if snapshot.row_count != 1:
            raise CommandError("Refused: browser fixture does not contain one row")
        self.stdout.write(
            self.style.SUCCESS(
                f"TRAINING ONLY: snapshot={snapshot.pk}; one fictional row; "
                "separate reviewer/publisher roles; no credentials printed"
            )
        )
